<?php

namespace App\Services;

use Carbon\Carbon;
use Illuminate\Support\Facades\DB;

use App\Models\ScheduledSardDaysModel;
use App\Models\ScheduledSardStageModel;

use App\Models\RecordSardDaysModel;
use App\Models\RecordSardStagesModel;

use App\Models\StudentModel;
use App\Models\User;
use App\Models\NotificationsModel;

class ScheduledSardCheckerService
{
    /*
    |--------------------------------------------------------------------------
    | الفحص الرئيسي
    |--------------------------------------------------------------------------
    |
    | هذه الدالة تفحص جميع جدولات السرد.
    |
    */

    public function checkAll()
    {
        $result = [
            'sard_days' => [
                'checked' => 0,
                'completed' => 0,
                'missed' => 0,
            ],

            'sard_stages' => [
                'checked' => 0,
                'completed' => 0,
                'missed' => 0,
            ],
        ];

        /*
        |--------------------------------------------------------------------------
        | فحص أيام السرد
        |--------------------------------------------------------------------------
        */

        $result['sard_days'] = $this->checkSardDays();

        /*
        |--------------------------------------------------------------------------
        | فحص مراحل السرد
        |--------------------------------------------------------------------------
        */

        $result['sard_stages'] = $this->checkSardStages();

        return $result;
    }


    /*
    |--------------------------------------------------------------------------
    | فحص Scheduled Sard Days
    |--------------------------------------------------------------------------
    */

    private function checkSardDays()
    {
        $checked = 0;
        $completed = 0;
        $missed = 0;

        $today = Carbon::today()->toDateString();

        /*
        |--------------------------------------------------------------------------
        | جلب كل المواعيد التي وصل تاريخها
        |--------------------------------------------------------------------------
        */

        $schedules = ScheduledSardDaysModel::whereDate(
            'sard_date',
            '<=',
            $today
        )->get();

        foreach ($schedules as $schedule) {

            $checked++;

            DB::beginTransaction();

            try {

                /*
                |--------------------------------------------------------------------------
                | البحث عن الطالب
                |--------------------------------------------------------------------------
                */

                $student = StudentModel::find(
                    $schedule->student_id
                );

                /*
                |--------------------------------------------------------------------------
                | إذا لم يوجد الطالب
                |--------------------------------------------------------------------------
                */

                if (!$student) {

                    $schedule->delete();

                    DB::commit();

                    continue;
                }


                /*
                |--------------------------------------------------------------------------
                | هل الطالب قام بالسرد؟
                |--------------------------------------------------------------------------
                |
                | نبحث بواسطة:
                |
                | student_id
                | sard_day
                |
                */

                $recordExists = RecordSardDaysModel::where(
                    'student_id',
                    $schedule->student_id
                )
                ->where(
                    'sard_day',
                    $schedule->sard_day
                )
                ->exists();


                /*
                |--------------------------------------------------------------------------
                | الطالب قام بالسرد
                |--------------------------------------------------------------------------
                */

                if ($recordExists) {

                    /*
                    | لا يوجد إشعار
                    | فقط نحذف الـ Schedule
                    */

                    $schedule->delete();

                    $completed++;

                    DB::commit();

                    continue;
                }


                /*
                |--------------------------------------------------------------------------
                | الطالب لم يقم بالسرد
                |--------------------------------------------------------------------------
                */

                $this->createMissedSardDayNotification(
                    $student,
                    $schedule
                );


                /*
                |--------------------------------------------------------------------------
                | بعد إنشاء الإشعار نحذف الـ Schedule
                |--------------------------------------------------------------------------
                */

                $schedule->delete();

                $missed++;

                DB::commit();

            } catch (\Exception $e) {

                DB::rollBack();

                /*
                |--------------------------------------------------------------------------
                | لا نوقف بقية الطلاب
                |--------------------------------------------------------------------------
                */

                continue;
            }
        }

        return [
            'checked' => $checked,
            'completed' => $completed,
            'missed' => $missed,
        ];
    }


    /*
    |--------------------------------------------------------------------------
    | إنشاء إشعار عدم سرد اليوم
    |--------------------------------------------------------------------------
    */

    private function createMissedSardDayNotification(
        $student,
        $schedule
    ) {

        /*
        |--------------------------------------------------------------------------
        | جلب اسم الطالب
        |--------------------------------------------------------------------------
        */

        $user = User::find($student->user_id);

        $studentName = $user
            ? $user->name
            : 'الطالب';


        /*
        |--------------------------------------------------------------------------
        | عنوان الإشعار
        |--------------------------------------------------------------------------
        */

        $title =
            'الطالب ' .
            $studentName .
            ' لم يسرد في موعد السرد المحدد';


        /*
        |--------------------------------------------------------------------------
        | منع تكرار الإشعار لنفس اليوم
        |--------------------------------------------------------------------------
        */

        $exists = NotificationsModel::where(
            'student_id',
            $student->id
        )
        ->where(
            'title',
            $title
        )
        ->whereDate(
            'insert_date',
            $schedule->sard_date
        )
        ->exists();


        if ($exists) {
            return;
        }


        /*
        |--------------------------------------------------------------------------
        | إنشاء الإشعار
        |--------------------------------------------------------------------------
        */

        NotificationsModel::create([

            'student_id' => $student->id,

            'halaqa_id' => $student->halaqa_id,

            'title' => $title,

            'notification_time' =>
                now()->format('G:i:s'),

            'insert_date' =>
                now()->toDateString(),

        ]);
    }


    /*
    |--------------------------------------------------------------------------
    | فحص Scheduled Sard Stage
    |--------------------------------------------------------------------------
    */

    private function checkSardStages()
    {
        $checked = 0;
        $completed = 0;
        $missed = 0;

        $today = Carbon::today()->toDateString();


        /*
        |--------------------------------------------------------------------------
        | جلب جميع مواعيد المراحل التي انتهى تاريخها
        |--------------------------------------------------------------------------
        */

        $schedules = ScheduledSardStageModel::whereDate(
            'sard_date',
            '<=',
            $today
        )->get();


        foreach ($schedules as $schedule) {

            $checked++;

            DB::beginTransaction();

            try {

                /*
                |--------------------------------------------------------------------------
                | جلب الطالب
                |--------------------------------------------------------------------------
                */

                $student = StudentModel::find(
                    $schedule->student_id
                );


                /*
                |--------------------------------------------------------------------------
                | الطالب غير موجود
                |--------------------------------------------------------------------------
                */

                if (!$student) {

                    $schedule->delete();

                    DB::commit();

                    continue;
                }


                /*
                |--------------------------------------------------------------------------
                | البحث عن سجل المرحلة
                |--------------------------------------------------------------------------
                |
                | نبحث عن:
                |
                | student_id
                | sard_type
                |
                */

                $recordExists =
                    RecordSardStagesModel::where(
                        'student_id',
                        $schedule->student_id
                    )
                    ->where(
                        'sard_type',
                        $schedule->sard_type
                    )
                    ->exists();


                /*
                |--------------------------------------------------------------------------
                | الطالب أكمل المرحلة
                |--------------------------------------------------------------------------
                */

                if ($recordExists) {

                    /*
                    | حذف الـ Schedule فقط
                    */

                    $schedule->delete();

                    $completed++;

                    DB::commit();

                    continue;
                }


                /*
                |--------------------------------------------------------------------------
                | الطالب لم يكمل المرحلة
                |--------------------------------------------------------------------------
                */

                $this->createMissedSardStageNotification(
                    $student,
                    $schedule
                );


                /*
                |--------------------------------------------------------------------------
                | حذف الـ Schedule بعد إنشاء الإشعار
                |--------------------------------------------------------------------------
                */

                $schedule->delete();

                $missed++;

                DB::commit();

            } catch (\Exception $e) {

                DB::rollBack();

                continue;
            }
        }


        return [
            'checked' => $checked,
            'completed' => $completed,
            'missed' => $missed,
        ];
    }


    /*
    |--------------------------------------------------------------------------
    | إشعار عدم إكمال مرحلة السرد
    |--------------------------------------------------------------------------
    */

    private function createMissedSardStageNotification(
        $student,
        $schedule
    ) {

        /*
        |--------------------------------------------------------------------------
        | جلب اسم الطالب
        |--------------------------------------------------------------------------
        */

        $user = User::find($student->user_id);

        $studentName = $user
            ? $user->name
            : 'الطالب';


        /*
        |--------------------------------------------------------------------------
        | عنوان الإشعار
        |--------------------------------------------------------------------------
        */

        $title =
            'الطالب ' .
            $studentName .
            ' لم يكمل ' .
            $schedule->sard_type .
            ' في الموعد المحدد';


        /*
        |--------------------------------------------------------------------------
        | منع التكرار
        |--------------------------------------------------------------------------
        */

        $exists = NotificationsModel::where(
            'student_id',
            $student->id
        )
        ->where(
            'title',
            $title
        )
        ->whereDate(
            'insert_date',
            $schedule->sard_date
        )
        ->exists();


        if ($exists) {
            return;
        }


        /*
        |--------------------------------------------------------------------------
        | إنشاء الإشعار
        |--------------------------------------------------------------------------
        */

        NotificationsModel::create([

            'student_id' => $student->id,

            'halaqa_id' => $student->halaqa_id,

            'title' => $title,

            'notification_time' =>
                now()->format('G:i:s'),

            'insert_date' =>
                now()->toDateString(),

        ]);
    }
}