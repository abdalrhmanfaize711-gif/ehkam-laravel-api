private function calculateHijriAge($birthDate)
{
    if (!$birthDate) {
        return null;
    }

    try {
        $today = Hijrian::hijri(now());

        $birth = explode('-', $birthDate);
        $current = explode('-', $today);

        $birthYear = (int) $birth[0];
        $birthMonth = (int) $birth[1];
        $birthDay = (int) $birth[2];

        $currentYear = (int) $current[0];
        $currentMonth = (int) $current[1];
        $currentDay = (int) $current[2];

        $age = $currentYear - $birthYear;

        if (
            $currentMonth < $birthMonth ||
            (
                $currentMonth == $birthMonth &&
                $currentDay < $birthDay
            )
        ) {
            $age--;
        }

        return $age;

    } catch (\Throwable $e) {
        return null;
    }
}
    public function getInfoPresnal(TeacherProfileRequest $request)
    {
        /*
        |--------------------------------------------------------------------------
        | Validation
        |--------------------------------------------------------------------------
        */

        $request->validate([
            'teacher_id' => 'required|integer|exists:teachers,id',
        ]);


        try {

            /*
            |--------------------------------------------------------------------------
            | جلب المعلم
            |--------------------------------------------------------------------------
            */

            $teacher = TeacherModel::with([
                'user'
            ])->findOrFail(
                $request->teacher_id
            );


            /*
            |--------------------------------------------------------------------------
            | البيانات
            |--------------------------------------------------------------------------
            */

            $data = [

                /*
                |--------------------------------------------------------------------------
                | بيانات المعلم
                |--------------------------------------------------------------------------
                */

                'teacher' => [

                    'id' => $teacher->id,

                    'user_id' => $teacher->user_id,

                    'name' => $teacher->user?->name,

                    'barthdate' => $teacher->user->barthdate,

                    'region' => $teacher->user?->region,

                    'join_date' => $teacher->user?->join_date,

                    'username' => $teacher->username,

                ],


                /*
                |--------------------------------------------------------------------------
                | الحضور
                |--------------------------------------------------------------------------
                */

                'attendance' => $this->getAttendance(
                    $teacher->user_id
                ),


                /*
                |--------------------------------------------------------------------------
                | الاختبارات
                |--------------------------------------------------------------------------
                */

                'exams' => $this->getExams(
                    $teacher->id
                ),

            ];


            /*
            |--------------------------------------------------------------------------
            | Success
            |--------------------------------------------------------------------------
            */

            return response()->json([

                'success' => true,

                'message' =>
                    'تم استرجاع ملف تعريف المعلم بنجاح.',

                'data' => $data,

            ], 200);


        } catch (\Throwable $e) {

            /*
            |--------------------------------------------------------------------------
            | Error
            |--------------------------------------------------------------------------
            */

            return response()->json([

                'success' => false,

                'message' =>
                    'فشل استرجاع ملف تعريف المعلم.',

                'error' =>
                    $e->getMessage(),

                'line' =>
                    $e->getLine(),

            ], 500);
        }
    }


    /*
    |--------------------------------------------------------------------------
    | ATTENDANCE
    |--------------------------------------------------------------------------
    |
    | attendance table تستخدم user_id
    |
    |--------------------------------------------------------------------------
    */

    private function getAttendance($userId)
    {
        /*
        |--------------------------------------------------------------------------
        | لا يوجد user
        |--------------------------------------------------------------------------
        */

        if (!$userId) {

            return [

                'total' => 0,

                'present' => 0,

                'absent' => 0,

                'late' => 0,

                'attendance_percentage' => 0,

                'records' => [],
            ];
        }


        /*
        |--------------------------------------------------------------------------
        | جلب سجلات الحضور
        |--------------------------------------------------------------------------
        */

        $records = AttendancesModel::where(
            'user_id',
            $userId
        )
        ->orderBy(
            'insert_date',
            'desc'
        )
        ->get();


        /*
        |--------------------------------------------------------------------------
        | إجمالي الأيام
        |--------------------------------------------------------------------------
        */

        $total = $records->count();


        /*
        |--------------------------------------------------------------------------
        | الحضور
        |--------------------------------------------------------------------------
        */

        $present = $records->filter(function ($record) {

            $state = trim(
                (string) $record->attendance_state
            );

            return in_array($state, [

                'حضور',

                'حاضر',

                'present',

                'Present',

            ]);

        })->count();


        /*
        |--------------------------------------------------------------------------
        | الغياب
        |--------------------------------------------------------------------------
        */

        $absent = $records->filter(function ($record) {

            $state = trim(
                (string) $record->attendance_state
            );

            return in_array($state, [

                'غياب',

                'غائب',

                'absent',

                'Absent',

            ]);

        })->count();


        /*
        |--------------------------------------------------------------------------
        | التأخير
        |--------------------------------------------------------------------------
        */

        $late = $records->filter(function ($record) {

            $state = trim(
                (string) $record->attendance_state
            );

            return in_array($state, [

                'تأخر',

                'متأخر',

                'late',

                'Late',

            ]);

        })->count();


        /*
        |--------------------------------------------------------------------------
        | نسبة الحضور
        |--------------------------------------------------------------------------
        */

        $attendancePercentage = $total > 0

            ? round(
                ($present / $total) * 100,
                2
            )

            : 0;


        /*
        |--------------------------------------------------------------------------
        | النتيجة
        |--------------------------------------------------------------------------
        */

        return [

            'total' => $total,

            'present' => $present,

            'absent' => $absent,

            'late' => $late,

            'attendance_percentage' =>
                $attendancePercentage,

            'records' => $records,
        ];
    }


    /*
    |--------------------------------------------------------------------------
    | EXAMS
    |--------------------------------------------------------------------------
    |
    | جميع الاختبارات التي أجراها المعلم
    |
    |--------------------------------------------------------------------------
    */

    private function getExams($teacherId)
    {
        /*
        |--------------------------------------------------------------------------
        | جلب الاختبارات
        |--------------------------------------------------------------------------
        */

        $records = RecoredExamsModel::where(
            'teacher_id',
            $teacherId
        )
        ->orderBy(
            'insert_date',
            'desc'
        )
        ->get();


        /*
        |--------------------------------------------------------------------------
        | عدد الاختبارات
        |--------------------------------------------------------------------------
        */

        $count = $records->count();


        /*
        |--------------------------------------------------------------------------
        | النسب
        |--------------------------------------------------------------------------
        */

        $percentages = $records
            ->pluck('final_percentage')
            ->filter(function ($value) {

                return $value !== null;

            })
            ->map(function ($value) {

                return (float) $value;

            });


        /*
        |--------------------------------------------------------------------------
        | عدد الناجحين
        |--------------------------------------------------------------------------
        |
        | اعتبرنا 50% فأعلى نجاح.
        |
        |--------------------------------------------------------------------------
        */

        $passed = $records->filter(function ($record) {

            return $record->final_percentage !== null
                && (float) $record->final_percentage >= 50;

        })->count();


        /*
        |--------------------------------------------------------------------------
        | عدد الراسبين
        |--------------------------------------------------------------------------
        */

        $failed = $records->filter(function ($record) {

            return $record->final_percentage !== null
                && (float) $record->final_percentage < 50;

        })->count();


        /*
        |--------------------------------------------------------------------------
        | الاختبارات المباغتة
        |--------------------------------------------------------------------------
        */

        $surpriseExams = $records->filter(function ($record) {

            return trim(
                (string) $record->exam_type
            ) === 'اختبار مباغت';

        })->count();


        /*
        |--------------------------------------------------------------------------
        | إجمالي الأسئلة
        |--------------------------------------------------------------------------
        */

        $totalQuestions = (int) $records->sum(
            'num_of_questions'
        );


        /*
        |--------------------------------------------------------------------------
        | إجمالي الأخطاء
        |--------------------------------------------------------------------------
        */

        $totalMistakes = (int) $records->sum(
            'total_mistakes'
        );


        /*
        |--------------------------------------------------------------------------
        | إجمالي اللحون
        |--------------------------------------------------------------------------
        */

        $totalMelodies = (int) $records->sum(
            'total_melodies'
        );


        /*
        |--------------------------------------------------------------------------
        | إجمالي الترددات
        |--------------------------------------------------------------------------
        */

        $totalHesitations = (int) $records->sum(
            'total_hesitiations'
        );


        /*
        |--------------------------------------------------------------------------
        | متوسط الدرجات
        |--------------------------------------------------------------------------
        */

        $averagePercentage =
            $percentages->count() > 0

                ? round(
                    $percentages->avg(),
                    2
                )

                : 0;


        /*
        |--------------------------------------------------------------------------
        | أعلى درجة
        |--------------------------------------------------------------------------
        */

        $highestPercentage =
            $percentages->count() > 0

                ? $percentages->max()

                : 0;


        /*
        |--------------------------------------------------------------------------
        | أقل درجة
        |--------------------------------------------------------------------------
        */

        $lowestPercentage =
            $percentages->count() > 0

                ? $percentages->min()

                : 0;


        /*
        |--------------------------------------------------------------------------
        | النتيجة
        |--------------------------------------------------------------------------
        */

        return [

            /*
            | عدد الاختبارات
            */

            'count' => $count,


            /*
            | الاختبارات المباغتة
            */

            'surprise_exams' => $surpriseExams,


            /*
            | عدد الناجحين
            */

            'passed' => $passed,


            /*
            | عدد الراسبين
            */

            'failed' => $failed,


            /*
            | متوسط الدرجات
            */

            'average_percentage' =>
                $averagePercentage,


            /*
            | أعلى درجة
            */

            'highest_percentage' =>
                $highestPercentage,


            /*
            | أقل درجة
            */

            'lowest_percentage' =>
                $lowestPercentage,


            /*
            | إجمالي الأسئلة
            */

            'total_questions' =>
                $totalQuestions,


            /*
            | إجمالي الأخطاء
            */

            'total_mistakes' =>
                $totalMistakes,


            /*
            | إجمالي اللحون
            */

            'total_melodies' =>
                $totalMelodies,


            /*
            | إجمالي الترددات
            */

            'total_hesitations' =>
                $totalHesitations,


            /*
            | جميع الاختبارات
            */

            'records' => $records,
        ];
    }
